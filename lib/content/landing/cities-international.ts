function toSlug(name: string, code: string): string {
  const base = name
    .toLowerCase()
    .replace(/[.']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return `${base}-${code.toLowerCase()}`;
}

/** Country codes whose search intent is in English. */
export const englishMarkets = new Set(
  Object.entries(countries)
    .filter(([, info]) => info.english)
    .map(([code]) => code)
);

export const internationalCities: (City & { countryCode: string; currency: string })[] = rows.map(
  ([name, code, metroTier, climate]) => {
    const country = countries[code];
    if (!country) throw new Error(`Missing country data for ${code}`);
    return {
      slug: toSlug(name, code),
      name,
      // `state` carries the country for international entries, so the existing
      // template renders "Manchester, United Kingdom" without special-casing.
      state: country.name,
      stateAbbr: code,
      metroTier,
      climate,
      timezone: country.tz,
      countryCode: code,
      currency: country.currency,
    };
  }
);
