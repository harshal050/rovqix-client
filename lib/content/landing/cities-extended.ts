function toSlug(name: string, abbr: string): string {
  const base = name
    .toLowerCase()
    .replace(/\./g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  // Several city names repeat across states (Springfield, Columbia, Portland,
  // Arlington). Suffix the state so slugs stay unique and the URL is clearer.
  return `${base}-${abbr.toLowerCase()}`;
}

